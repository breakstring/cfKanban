export type TranslationKey = keyof typeof translations.en;
const STORAGE_KEY = "cfkanban_locale";

function initialLocale(): Locale {
  if (typeof window === "undefined") return "en";
  return resolveLocalePreference(
    readStoredLocale(() => window.localStorage, STORAGE_KEY),
    window.navigator.languages,
  );
}

export const locale = ref<Locale>(initialLocale());
export const htmlLanguage = computed(() => locale.value);

watch(locale, (value) => {
  if (typeof document === "undefined" || typeof window === "undefined") return;
  document.documentElement.lang = value;
  writeStoredLocale(() => window.localStorage, STORAGE_KEY, value);
}, { immediate: true });

export function setLocale(value: Locale): void {
  locale.value = value;
}

export function t(key: TranslationKey): string {
  return translations[locale.value][key] ?? translations.en[key];
}
